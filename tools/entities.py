#!/usr/bin/env python3
"""Generate src/entities.bend from the HTML Standard's named character
references table (https://html.spec.whatwg.org/entities.json).

Usage: python3 tools/entities.py entities.json > src/entities.bend

Every entry of entities.json becomes one `Ref{name, first, second}` row: the
name without its leading `&` (with its `;` when the table has one, so the
legacy names appear twice, with and without), and the one or two code points
it stands for (`second` is 0 when there is one). Rows are sorted by name.
"""
import json
import sys


def main(path):
    with open(path, encoding="utf-8") as f:
        table = json.load(f)
    rows = []
    for key, entry in table.items():
        assert key.startswith("&")
        name = key[1:]
        cps = entry["codepoints"]
        assert 1 <= len(cps) <= 2 and all(cp != 0 for cp in cps)
        assert chr(cps[0]) + (chr(cps[1]) if len(cps) == 2 else "") \
            == entry["characters"]
        assert name.isascii() and name.isalnum() or name[:-1].isalnum()
        rows.append((name, cps[0], cps[1] if len(cps) == 2 else 0))
    rows.sort()
    out = sys.stdout
    out.write("# ezhttp/src/entities: the HTML Standard's named character "
              "references\n")
    out.write("# (HTML §13.5, https://html.spec.whatwg.org/entities.json), "
              "%d names.\n" % len(rows))
    out.write("# Generated by tools/entities.py; do not edit by hand.\n"
              "#\n"
              "# Trusted, not proved: this is the HTML Standard's named character\n"
              "# references table: every name in it once, without its leading `&`, with the\n"
              "# one or two code points it stands for. tools/entities.py generates it from\n"
              "# the standard's entities.json (https://html.spec.whatwg.org/entities.json,\n"
              "# the same table as Python's `html.entities.html5`), checking that each\n"
              "# entry's code points spell its characters; no law reaches that: a law can\n"
              "# say how the table is read (laws/NamedReferencesLongestMatch.bend), not\n"
              "# that its rows are the standard's. No test compares html_unescape against\n"
              "# Python's `html.unescape`.\n")
    out.write("import Base\n\n")
    out.write("# one named character reference: its name (with its `;` when "
              "it has one)\n# and the one or two code points it stands for, "
              "`second` 0 when one\n")
    out.write("type Ref is Data:\n  Ref{name: String, first: U32, "
              "second: U32}\n\n")
    out.write("# every named character reference, sorted by name\n")
    out.write("def table() -> List<&2, Ref>:\n  [\n")
    for i, (name, a, b) in enumerate(rows):
        sep = "," if i + 1 < len(rows) else ""
        out.write('    Ref{"%s", %d, %d}%s\n' % (name, a, b, sep))
    out.write("  ]\n")


if __name__ == "__main__":
    main(sys.argv[1])
